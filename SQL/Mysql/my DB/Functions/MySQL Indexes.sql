-- MySQL Indexes
-- they are helpful tools, spending up data searches,
-- they help retrieve specific information quickly.

-- types of indexes --
-- 1. Primary Index
-- is automaticallly created when a primary key is defined on the table'
-- uniquely identifies each row in the table

-- 2. Unique index
-- it ensures all the values within a row are unique.
-- contrary to the primary index, a table may contain several unique indexes.

-- 3. full-text index
-- is used with columns storing large quantites of text and facilitates very fast recovery of data based on complicated text-based searches.

-- 4. Composite Index
-- A composite index is an index created on more than one column.

-- 5. Spatial Index
-- Spatial indexes are applied to geographic data types and enable the effective management and querying of spatial data. 
-- useful in applications that involve mapping, location-based services, and geographic information systems.


