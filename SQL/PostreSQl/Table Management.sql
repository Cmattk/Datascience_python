--- Comparing Tables --- 
-- commonly used techniques for comparing tables:
-- Using EXCEPT and UNION operators
-- Using OUTER JOIN

CREATE TABLE foo(
    id int PRIMARY KEY,
    name VARCHAR (50)
);

INSERT INTO foo (id, name)
VALUES
    (1,'a'), (2,'b');

CREATE TABLE bar(
    id int PRIMARY KEY,
    name VARCHAR (50)
);

INSERT INTO bar (id,name)
VALUES 
    (1, 'a'),
    (2, 'b');

UPDATE bar
SET name = 'c'
WHERE id = 2;

-- identify difference using EXCEPT
-- find the rows in the 'foo' table but not in the bar table
select id, name, 'not in bar' AS note 
FROM foo
EXCEPT 
    SELECT id, name, 'not in bar' AS note 
    FROM bar;

SELECT * FROM bar
EXCEPT SELECT * FROM foo;

-- Comparison using OUTER JOIN
-- It returns all rows when there is a match in either table, and fills with NULL where there is no match.
SELECT * from foo
FULL OUTER JOIN bar USING(id,name)
WHERE 
    foo.id IS NULL
    or bar.id IS NULL;

SELECT
    COUNT(*)
FROM
    foo
FULL OUTER JOIN bar USING (id,name)
WHERE 
    foo.id IS NULL
    OR bar.id IS NULL;

/*
EXCEPT-UNION: Best when you need clear, distinct differences between two datasets.
FULL OUTER JOIN: Useful for detailed comparisons, especially when working with complex datasets.
*/


