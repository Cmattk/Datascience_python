-- UPSERT Operation --
-- llows users to either insert a new row into a table or update an existing row if it already exists.

/*
# syntax:

INSERT INTO table_name (column1, column2, ...)
VALUES (value1, value2, ...)
ON CONFLICT (conflict_column)
DO NOTHING | DO UPDATE SET column1 = value1, column2 = value2, ...;

Use DO NOTHING to skip the insert if a conflict occurs, or
Use DO UPDATE to update the existing row with new values based on the conflict.

*/

CREATE TABLE inventory2(
    id SERIAL PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    price DECIMAL (10,2) NOT NULL,
    quantity INT NOT NULL
);

INSERT INTO inventory2 (name, price, quantity)
VALUES 
    ('Item A', 10.99, 100),
    ('Item B', 15.49, 200),
    ('Item C', 20.00, 150);

SELECT * FROM inventory2;

-- 

INSERT INTO inventory2 (id, name, price, quantity)
VALUES (1, 'Item A', 12.99, 120)
ON CONFLICT (id)
DO UPDATE SET
    price = EXCLUDED.price,
    quantity = EXCLUDED.quantity;

INSERT INTO inventory2 (id, name, price, quantity)
VALUES (4, 'Item D', 25.99, 80)
ON CONFLICT (id)
DO UPDATE SET
    price = EXCLUDED.price,
    quantity = EXCLUDED.quantity;


-- Using ON CONFLICT DO NOTHING
INSERT INTO inventory2 (id, name, price, quantity)
VALUES (1, 'Item A', 30.00, 100)
ON CONFLICT (id)
DO NOTHING;

SELECT * FROM inventory2;

