-- Identity Column -- 
-- identity column is a specialized column type that automatically generates unique values for each row, making it ideal for primary keys and other unique identifiers. 
-- Syntax
-- column_name type GENERATED { ALWAYS | BY DEFAULT } AS IDENTITY[ ( sequence_option ) ]

-- generated always
create table color (
    color_id int generated always as identity,
    color_name varchar not null
);

insert into color (color_name)
values ('Red');
select  *  from color;

insert into color (color_id, color_name)
values (2, 'Green');

insert into color(color_id, color_name)
OVERRIDING SYSTEM VALUE
VALUES (2, 'Green');

--  generated by default
drop table color;

CREATE TABLE color(
    color_id int generated by default as identity,
    color_name VARCHAR NOT NULL
);

