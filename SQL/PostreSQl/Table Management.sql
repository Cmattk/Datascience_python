-- different roles in application 
CREATE TABLE role(
    role_id serial PRIMARY KEY,
    role_name VARCHAR (255) UNIQUE NOT NULL
);

-- account_role - to manage the relationship between users and roles
CREATE TABLE account_role(
    user_id INTEGER NOT NULL,
    role_id INTEGER NOT NULL,
    grant_date TIMESTAMP without time zone,
    PRIMARY KEY (user_id, role_id),
    CONSTRAINT account_role_role_id_fk FOREIGN KEY (role_id)
        REFERENCES role (role_id) MATCH SIMPLE
        ON UPDATE NO ACTION
        ON DELETE NO ACTION,
    CONSTRAINT account_role_user_id_fk FOREIGN KEY (user_id)
        REFERENCES account (user_id) MATCH SIMPLE
        ON UPDATE NO ACTION
        ON DELETE NO ACTION
);

/*
The primary key constraint ensures that each combination of 'user_id' and 'role_id' is unique.
PRIMARY KEY (user_id, role_id)

The foreign key constraint ensures that the values in a column match values in another table, creating a relationship between tables.
This helps maintain referential integrity across the database.
FOREIGN KEY (column) REFERENCES other_table (column) 
    ON DELETE CASCADE 
    ON UPDATE CASCADE

The unique constraint ensures that all values in a column are distinct across the table.
UNIQUE (column)

NOT NULL constraint ensures that a column cannot contain a NULL value, enforcing data integrity.
column_name datatype NOT NULL
*/

-- 2. - SELECT INTO --
-- allows users to create a new table directly from the result set of a query.
-- SELECT INTO does not return data to the client but saves it in a new table.
-- syntax --
/*
SELECT column_list
INTO [TEMPORARY | TEMP | UNLOGGED] [TABLE] new_table_name
FROM table_name
WHERE condition;
*/

SELECT film_id, title, rental_rate
INTO TABLE film_r
FROM film
WHERE rating = 'R' AND rental_duration = 5
ORDER BY title;

SELECT
    film_id,
    title,
    length 
INTO TEMP TABLE short_film
FROM
    film
WHERE
    length < 60
ORDER BY
    title;

