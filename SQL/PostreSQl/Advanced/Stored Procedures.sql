--- join table --
SELECT 
    RANK() OVER (ORDER BY t.points DESC) AS Position,
    t.name as Club,
    t.points as Points,
    l.league_name AS League
FROM team AS t
JOIN league AS l ON t.league_id = l.league_id;


--- ranking teams in top 5 leagues
SELECT 
    RANK() OVER (ORDER BY t.points desc) as Position,
    t.name as Team,
    t.points as points,
    l.league_name as League
FROM team AS t 
JOIN league as l on t.league_id = l.league_id
WHERE l.league_id BETWEEN 1 AND 5; -- or <= 5


--- drop procedure
-- Syntax
-- DROP PROCEDURE [IF EXISTS] procedure_name (argument_list)
-- [CASCADE | RESTRICT];

-- CASCADE: Drops the procedure and its dependent objects.
-- RESTRICT: Default option; prevents dropping the procedure if it has dependent objects.

CREATE OR REPLACE PROCEDURE insert_actor(
    fname VARCHAR, 
    lname VARCHAR)
LANGUAGE plpgsql    
AS $$
BEGIN
    INSERT INTO actor(first_name, last_name)
    VALUES(fname, lname);
END;
$$;

DROP PROCEDURE insert_actor(VARCHAR, VARCHAR);

-- uses the 'split_part()' function to split the full name into first name and last name 
-- before inserting them into the actor table.
CREATE OR REPLACE PROCEDURE insert_actor(
    full_name VARCHAR
)
LANGUAGE plpgsql    
AS $$
DECLARE
    fname VARCHAR;
    lname VARCHAR; 
BEGIN
    SELECT 
        SPLIT_PART(full_name, ' ', 1),
        SPLIT_PART(full_name, ' ', 2)
    INTO fname,
         lname;

    INSERT INTO actor(first_name, last_name)
    VALUES(fname, lname);    
END;
$$;

DROP PROCEDURE insert_actor(VARCHAR);

--- procedure to  deletes an actor by id
CREATE OR REPLACE PROCEDURE delete_actor(
    p_actor_id INT
)
LANGUAGE plpgsql
AS $$
BEGIN
    DELETE FROM actor 
    WHERE actor_id = p_actor_id;
END; 
$$;

DROP PROCEDURE delete_actor;
