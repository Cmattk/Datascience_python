-- Stored Procedures
-- The store procedures define functions for creating triggers or custom aggregate functions.
-- Stored procedures provide a means to execute multiple SQL statements in a structured and reusable way.

-- They introduce advanced control structures and allow us to perform complex calculations, making it easier to build complex applications directly within the database.
-- PostgreSQL supports three main procedural languages: SQL, PL/pgSQL, and C. We can also add other languages, such as Perl, Python, and TCL, through extensions.

-- PostgreSQL divides procedural languages into two main categories:
-- Safe Languages: These can be used by any user and include languages like SQL and PL/pgSQL.
-- Sandboxed Languages: These are restricted to superusers because they can bypass security measures and access external resources. An example of a sandboxed language is C.

-- using PostgreSQL stored procedures:
-- Reduced network traffic: Stored procedures execute on the database server, so the application sends a single function call instead of multiple SQL statements, reducing the number of database round trips.
-- Increased performance: Increase application performance because the user-defined functions and stored procedures are pre-compiled and stored in the PostgreSQL database server.
-- Reusability: You can reuse stored procedures across multiple applications, making database management more efficient.
-- Centralized logic: With stored procedures, logic is centralized on the database server, which reduces the redundancy of code in different applications.

-- cons
-- Specialized skills required: Slowness in software development because stored procedure programming requires specialized skills that many developers do not possess.
-- Version management: Difficult to manage versions and hard to debug.
-- Portability issues: May not be portable to other database management systems e.g., MySQL or Microsoft SQL Server.



-- create a stored procedure that transfers funds from one account to another in a banking system.
drop table if exists accounts;

CREATE TABLE accounts (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,
    balance NUMERIC(15, 2) NOT NULL,
    currency CHAR(3) NOT NULL,  -- 'USD', 'EUR', 'KES', etc.
    PRIMARY KEY(id)
);

-- Function to Format Balance with Currency Symbol.
CREATE OR REPLACE FUNCTION format_currency(amount NUMERIC, currency_code CHAR(3))
RETURNS TEXT 
AS $$
BEGIN
    RETURN
        case currency_code
            WHEN 'USD' THEN '$' || to_char(amount, 'FM999,999,999.00')
            WHEN 'EUR' THEN '€' || to_char(amount, 'FM999,999,999.00')
            WHEN 'KES' THEN 'KSh' || TO_CHAR(amount, 'FM999,999,999.00')
            WHEN 'GBP' THEN '£' || TO_CHAR(amount, 'FM999,999,999.00')
            ELSE currency_code || ' ' || TO_CHAR(amount, 'FM999,999,999.00')
        END;
END;
$$ LANGUAGE  plpgsql;

insert into accounts(name, balance, currency)
values('Raju', 170000,'KES'),
      ('Nikhil', 410000,'KES'),
      ('Manu', 230000,'KES'),
      ('Patel', 5672500,'KES'),
      ('Kenny', 542000,'KES');
SELECT * FROM accounts;
SELECT name, format_currency(balance, currency) as formatted_balance
FROM accounts;

-- stored procedure to transfer funds.
CREATE OR REPLACE PROCEDURE transfer(
    sender int,
    receiver int,
    amount decimal
)
AS $$
BEGIN
    -- Check if sender exists
    IF NOT EXISTS (SELECT 1 FROM accounts WHERE id = sender) THEN
        RAISE EXCEPTION 'Sender account (ID: %) does not exist', sender;
    END IF;

    -- Check if receiver exists
     IF NOT EXISTS (SELECT 1 FROM accounts WHERE id = receiver) THEN
        RAISE EXCEPTION 'Receiver account (ID: %) does not exist', receiver;
    END IF;

    -- Check if sender has enough balance
    IF (SELECT balance FROM accounts WHERE id = sender) < amount THEN
        RAISE EXCEPTION 'Insufficient Funds In sender''s account';
    END IF;

    -- subtracting amount from the sender
    UPDATE accounts
    SET balance = balance - amount
    WHERE id = sender;

    -- adding the amount to the receiver
    UPDATE accounts
    SET balance = balance + amount
    WHERE id = receiver;

    -- No COMMIT here; it is controlled by the client or outer transaction block

EXCEPTION WHEN OTHERS THEN
    -- any error will rollback the entire transaction
    RAISE NOTICE 'Transfer failed: %', SQLERRM;
    RAISE;
END;
$$ LANGUAGE plpgsql;

