-- $$: Dollar-quoted string constant syntax to define the body of the stored procedure.

-- a procedure that inserts a record into an teams table.
CREATE TABLE team(
    id SERIAL PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    points INT NOT NULL
);

CREATE OR REPLACE PROCEDURE add_team(team_name VARCHAR(255), team_points INT)
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO team (name, points) VALUES (team_name, team_points);
END;
$$;

CALL add_team('FC Barcelona', 101);
CALL add_team('Real Madrid', 92);
-- ...
SELECT * FROM team;

-- procedure to update the table
CREATE OR REPLACE PROCEDURE update_team(team_name VARCHAR(255), new_points INT)
LANGUAGE plpgsql
AS $$
BEGIN
    -- check if the team exist
    IF NOT EXISTS (SELECT 1 FROM team where name = team_name) THEN
        RAISE EXCEPTION 'The team %, does not exist', team_name;
    END IF;

    UPDATE team SET points = new_points WHERE name = team_name;
END;
$$;

CALL update_team('Simba', 45);
CALL update_team('FC Barcelona', 96);

SELECT * FROM team ORDER BY points DESC;

--- procedure to add new column
CREATE OR REPLACE PROCEDURE add_column(
    column_name TEXT, column_type TEXT
)

LANGUAGE plpgsql
AS $$
BEGIN
    EXECUTE format('ALTER TABLE team ADD COLUMN IF NOT EXISTS %I %s', column_name, column_type);
    RAISE NOTICE 'column % of type % has been added', column_name, column_type;
END;
$$;

